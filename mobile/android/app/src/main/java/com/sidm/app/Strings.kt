    fun get(lang: String, key: String, vararg args: Any?): String {
        var text = (if (lang == "bn") bn[key] else null) ?: en[key] ?: key
        args.forEachIndexed { i, a -> text = text.replace("{$i}", a?.toString() ?: "") }
        return text
    }

    /** The language name shown in its own script. */
    fun languageName(code: String) = if (code == "bn") "বাংলা" else "English"

    /**
     * Turns an error code from the engine ("errAccess:403", "errDrm",
     * "errOther:some text") into a sentence.
     */
    fun error(lang: String, code: String?): String {
        if (code.isNullOrBlank()) return get(lang, "stFailed")
        val key = code.substringBefore(':')
        val arg = code.substringAfter(':', "")
        return if (en.containsKey(key)) get(lang, key, arg) else code
    }

    /** All keys, for the test that checks both languages have every string. */
    internal fun keys(lang: String) = (if (lang == "bn") bn else en).keys
}

val LocalLang = compositionLocalOf { "en" }

@Composable
fun t(key: String, vararg args: Any?): String = Strings.get(LocalLang.current, key, *args)
